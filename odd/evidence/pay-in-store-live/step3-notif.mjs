// Step 3: the bell lists the SALE_HOLD_REVIEW notice for 000078; a click opens the sale.
import { makeLog, open, settle, shot, BASE } from './lib.mjs'
const log = makeLog('step3-notif')
const { browser, page, foreign } = await open(log)
page.setDefaultTimeout(10000)
await page.goto(`${BASE}/pos/ventas`, { waitUntil: 'domcontentloaded' })
await settle(page, 1000)
const bell = page.getByRole('button', { name: /^Notificaciones,/ }).first()
log('bell label ' + JSON.stringify(await bell.getAttribute('aria-label')))
await bell.click()
await settle(page, 1000)
const row = page.locator('li.nt').filter({ hasText: 'A-202611-000078' }).first()
await row.waitFor()
const href = await row.locator('.nt-link').getAttribute('href')
log('ROW text ' + JSON.stringify((await row.innerText()).replace(/\s+/g, ' ')))
log('ROW href ' + href + ' type=' + JSON.stringify(await row.getByTestId('notification-type').innerText().catch(() => null)))
await row.scrollIntoViewIfNeeded()
await shot(page, '10-bell-panel', log)
await row.locator('.nt-link').click()
await page.waitForURL((u) => u.pathname.startsWith('/pos/ventas/c146d74e'), { timeout: 10000 }).catch(() => {})
await settle(page, 1000)
log('URL after click ' + new URL(page.url()).pathname)
const hold = page.getByTestId('sale-detail-hold')
log('detail hold card on 000078 visible=' + (await hold.isVisible().catch(() => false)))
await shot(page, '11-sale-78-from-notification', log)
log('FOREIGN ' + JSON.stringify([...foreign]))
await browser.close()
