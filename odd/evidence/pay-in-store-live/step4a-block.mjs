// Step 4a: CASH on 000077 without an open till → block «Abre tu caja…» + «Ir a Caja». No payment sent.
import { makeLog, open, settle, shot, BASE, logBodies } from './lib.mjs'
const log = makeLog('step4a-block')
const { browser, page, foreign } = await open(log)
page.setDefaultTimeout(10000)
logBodies(page, log)
await page.goto(`${BASE}/pos/ventas/6e64f7bc-f7a8-48cb-8c5f-8902ef000233`, { waitUntil: 'domcontentloaded' })
await settle(page, 1000)
await page.getByRole('button', { name: 'Registrar pago' }).first().click()
await page.getByTestId('payment-method-tile-cash').click()
await settle(page, 800)
const missing = page.getByTestId('debt-cash-session-missing')
log('BLOCK visible=' + (await missing.isVisible().catch(() => false)) + ' text=' + JSON.stringify((await missing.innerText().catch(() => '')).replace(/\s+/g, ' ')))
log('pick/other ' + JSON.stringify({ pick: await page.getByTestId('debt-cash-session-pick').count(), error: await page.getByTestId('debt-cash-session-error').count() }))
log('confirm enabled ' + (await page.getByTestId('confirm-debt-payment').isEnabled()))
await shot(page, '12-cash-block', log)
await page.getByTestId('debt-cash-session-open-caja').click()
await page.waitForURL((u) => u.pathname.startsWith('/pos/caja'), { timeout: 10000 }).catch(() => {})
await settle(page, 1200)
log('URL after Ir a Caja ' + new URL(page.url()).pathname)
const regs = await page.$$eval('[data-testid^="cash-register-open-"]', (els) => els.map((e) => ({ id: e.getAttribute('data-testid').replace('cash-register-open-', ''), text: e.closest('tr,article')?.textContent?.replace(/\s+/g, ' ').trim().slice(0, 160) })))
log('OPENABLE ' + JSON.stringify(regs))
await shot(page, '13-caja', log)
log('FOREIGN ' + JSON.stringify([...foreign]))
await browser.close()
