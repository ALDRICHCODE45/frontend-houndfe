import { open, settle, shot, makeLog, BASE, logBodies } from './lib.mjs'
const log = makeLog('step4-handover')
const { browser, page, issues } = await open(log, { role: 'cashier' })
logBodies(page, log, ['kind', 'declaredCents', 'amountCents'])
await page.goto(`${BASE}/pos/caja`); await settle(page, 1200)
log('head: ' + (await page.locator('.cash-head-meta').innerText()).replace(/\s+/g, ' ') + ' / ' + await page.getByTestId('cash-head-title').innerText())
await page.getByTestId('cash-next-primary').click(); await settle(page, 600)
const form = page.getByTestId('cash-handover-form')
log('form visible=' + await form.isVisible() + ' uuid-like inputs=' + await form.locator('input[type=text], input:not([type])').evaluateAll((els) => els.map((e) => e.closest('[data-testid]')?.dataset.testid + '|' + (e.placeholder || '')).join(',')))
log('text-input labels: ' + (await form.locator('label').allInnerTexts()).map((s) => s.replace(/\s+/g, ' ')).join(' | '))
async function declare(kind, amount, who, note) {
  await form.getByText(kind === 'FLOAT' ? 'Fondo' : 'Retiro', { exact: true }).click()
  await settle(page, 500)
  log(`${kind} recipients: ` + (await page.locator('[data-testid^="cash-handover-recipient-card-"]').allInnerTexts()).map((s) => s.replace(/\s+/g, ' ')).join(' | '))
  await page.locator('[data-testid^="cash-handover-recipient-card-"]', { hasText: who }).click()
  await page.getByTestId('cash-handover-amount').fill(amount)
  await page.getByTestId('cash-handover-notes').fill(note)
  await form.scrollIntoViewIfNeeded()
  await shot(page, `12-cashier-handover-${kind.toLowerCase()}-form-1440-light`, log)
  await page.getByTestId('cash-handover-submit').click(); await settle(page, 1200)
  log(`after ${kind}: list=` + (await page.getByTestId('cash-handover-list').innerText().catch(() => 'NONE')).replace(/\s+/g, ' ') + ' err=' + (await page.getByTestId('cash-custody-actions-error').innerText().catch(() => '-')))
}
await declare('FLOAT', '100', 'Manager Centro', 'Fondo siguiente turno QA T6')
await declare('WITHDRAWAL', '450', 'Manager Centro', 'Retiro QA T6')
log('release blocked: ' + (await page.getByTestId('cash-drawer-release-blocked').innerText().catch(() => '-')) + ' releaseBtn disabled=' + await page.getByTestId('cash-drawer-release').isDisabled().catch(() => 'n/a'))
await page.getByTestId('cash-handover-list').scrollIntoViewIfNeeded()
await shot(page, '13-cashier-handovers-declared-1440-light', log)
log('ISSUES ' + JSON.stringify(issues))
await browser.close()
