import { open, settle, shot, makeLog, BASE, logBodies } from './lib.mjs'
const log = makeLog('step5-receive')
const { browser, page, issues } = await open(log, { role: 'manager' })
logBodies(page, log, ['receivedCents', 'declaredCents'])
await page.goto(`${BASE}/pos/caja`); await settle(page, 1500)
log('receive entry: ' + (await page.getByTestId('cash-receive-entry').innerText()).replace(/\s+/g, ' '))
await page.getByTestId('cash-receive-entry').click(); await settle(page, 800)
const cards = page.locator('[data-testid^="cash-custody-pending-"]:not([data-testid="cash-custody-pending-empty"])')
log('pending cards: ' + await cards.count())
const mine = cards.filter({ hasText: 'QA T6' })
log('QA T6 cards: ' + await mine.count())
await mine.first().scrollIntoViewIfNeeded()
await shot(page, '14-manager-por-recibir-1440-light', log)
for (let i = 0; i < 2; i++) {
  const card = cards.filter({ hasText: 'QA T6' }).first()
  const id = (await card.getAttribute('data-testid')).replace('cash-custody-pending-', '')
  const declared = (await page.getByTestId(`cash-custody-declared-${id}`).innerText()).replace(/[^0-9.]/g, '')
  const input = page.getByTestId(`cash-custody-received-input-${id}`)
  log(`card ${id.slice(0, 8)} declared=${declared} prefilled="${await input.inputValue()}"`)
  if (!(await input.inputValue())) await input.fill(declared)
  const btn = page.getByTestId(`cash-custody-receive-${id}`)
  log('button: ' + await btn.innerText())
  await btn.click(); await settle(page, 1500)
  log('status: ' + (await page.getByTestId('cash-custody-status').innerText().catch(() => '')))
}
await shot(page, '15-manager-received-1440-light', log)
log('ISSUES ' + JSON.stringify(issues))
await browser.close()
