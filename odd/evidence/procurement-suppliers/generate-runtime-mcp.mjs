// Local preparation only: inline canonical code so the MCP VM needs no modules.
import { readFile, writeFile } from 'node:fs/promises'
import vm from 'node:vm'

const source = await readFile(new URL('./runtime-checks.mjs', import.meta.url), 'utf8')
const marker = 'export async function run('
if (source.split(marker).length !== 2) throw new Error('Expected one canonical run export')
if (/\b(?:require|process)\b|node:|file:\/\/\//.test(source)) throw new Error('Host module/runtime dependency in MCP source')
const mountedSource = '/@fs/home/aldrich_coder45/Desktop/workspace/houndfe/frontend-houndfe/src/'
const browserImports = new Set([
  `${mountedSource}features/auth/stores/useAuthStore.ts`,
  `${mountedSource}app/router/index.ts`,
  `${mountedSource}features/procurement/suppliers/api/suppliers.api.ts`,
])
for (const match of source.matchAll(/\bimport\(([^)]+)\)/g)) {
  const literal = /^(['"])([^'"]+)\1$/.exec(match[1])
  if (!literal || !browserImports.has(literal[2])) throw new Error('Expected exact mounted-app browser module URL')
}
for (const stage of ['manager', 'permissions', 'delete']) {
  const output = `async (page) => {\n// Generated by generate-runtime-mcp.mjs; edit runtime-checks.mjs instead.\n${source.replace(marker, 'async function run(')}\nreturn await run(page, '${stage}');\n}\n`
  const script = new vm.Script(`(${output})`)
  if (typeof script.runInNewContext(Object.create(null)) !== 'function') throw new Error('Expected async MCP function')
  const filename = `mcp-runtime-${stage}.js`
  await writeFile(new URL(`./${filename}`, import.meta.url), output)
  console.log(`${filename}: self-contained expression generated and parsed in empty VM; not invoked`)
}
