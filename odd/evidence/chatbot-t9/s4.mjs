import { open, shot, BASE } from './lib.mjs'
const w = Number(process.argv[2] ?? 1440)
const { browser, page, log } = await open({ width: w, height: w < 500 ? 844 : 900 })
const blocked = []
await page.route(/:3003\/chatbot-/, (route) => { const r = route.request(); if (r.method() !== 'GET') { blocked.push(r.method() + ' ' + r.url()); return route.abort() } return route.continue() })
await page.goto(`${BASE}/chatbot/solicitudes/5f35aff8-4047-42c8-9609-808dc67a9220`, { waitUntil: 'domcontentloaded' })
await page.waitForLoadState('networkidle', { timeout: 20000 }).catch(() => {})
await page.waitForTimeout(2000)
const open_ = page.getByRole('button', { name: /Responder/ }).first()
await open_.click()
await page.waitForTimeout(1200)
await shot(page, `reply-form-open-${w}`)
const dlg = page.locator('[role=dialog]').last()
console.log((await dlg.innerText()).replace(/\n+/g, ' | '))
const ta = dlg.locator('textarea')
console.log('textarea attrs', await ta.evaluate(e => ({ max: e.maxLength, ph: e.placeholder, label: e.getAttribute('aria-label'), id: e.id })))
console.log('buttons in dialog:', await dlg.locator('button').evaluateAll(b => b.map(x => `${(x.innerText||'').trim()||x.getAttribute('aria-label')}[dis=${x.disabled}]`)))
// empty submit
const send = dlg.getByRole('button', { name: /Enviar|Responder/ }).last()
console.log('send button', await send.innerText(), 'disabled?', await send.isDisabled())
if (!(await send.isDisabled())) { await send.click(); await page.waitForTimeout(800) }
console.log('after empty submit:', (await dlg.innerText()).replace(/\n+/g, ' | '))
await shot(page, `reply-form-empty-validation-${w}`)
await ta.fill('Hola'); await page.waitForTimeout(300)
console.log('counter after 4 chars:', (await dlg.innerText()).match(/\d+\s*\/\s*1500/g))
await ta.fill('x'.repeat(1500)); console.log('1500 counter', (await dlg.innerText()).match(/\d+\s*\/\s*1500/g), 'len', await ta.evaluate(e=>e.value.length))
await ta.fill('x'.repeat(1600)); console.log('1600 -> len', await ta.evaluate(e=>e.value.length))
await ta.fill('   '); await page.waitForTimeout(300)
console.log('whitespace-only send disabled?', await send.isDisabled())
await ta.fill('')
// close without sending
const close = dlg.getByRole('button', { name: /Cancelar|Cerrar|Volver/ }).first()
console.log('close button', await close.innerText().catch(()=> 'n/a'))
await page.keyboard.press('Escape'); await page.waitForTimeout(800)
console.log('dialog open after Escape?', await page.locator('[role=dialog]').count())
console.log('BLOCKED non-GET attempts:', blocked, 'CONSOLE', log.console, 'FAILED', log.failed)
await browser.close()
