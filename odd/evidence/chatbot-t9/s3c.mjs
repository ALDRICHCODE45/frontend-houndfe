import { open, shot, BASE } from './lib.mjs'
const w = Number(process.argv[2] ?? 1440)
const { browser, page, log } = await open({ width: w, height: w < 500 ? 844 : 900 })
await page.goto(`${BASE}/chatbot/solicitudes/44e0e4e1-56fb-419a-96cd-1a48e04db5b5`, { waitUntil: 'domcontentloaded' })
await page.waitForLoadState('networkidle', { timeout: 20000 }).catch(() => {})
await page.waitForTimeout(2000)
await page.getByTestId('media-load-audio').scrollIntoViewIfNeeded()
await page.getByTestId('media-load-audio').click()
await page.waitForTimeout(2500)
console.log(await page.locator('.rc-log [data-kind=audio]').first().evaluate(e => e.outerHTML.slice(0, 700)))
await page.locator('.rc-log [data-kind=audio]').first().scrollIntoViewIfNeeded()
await shot(page, `conv-audio-player-${w}`)
console.log('PDF chip:', await page.getByTestId('media-pdf').evaluate(e => ({ tag: e.tagName, href: e.getAttribute('href'), target: e.getAttribute('target') })))
console.log(log.requests.filter(x => /media/.test(x)).join(' ; '), 'CONSOLE', log.console, 'FAILED', log.failed)
await browser.close()
